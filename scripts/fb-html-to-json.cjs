// Converts the posts of a Facebook "Download your information" export in HTML format into the JSON format
// scripts/fb-archive-trip.cjs reads (your_posts_1.json), so the usual pipeline can run on it.
// Posts missing from the export (copied from the page by hand) are added without media, so their photos
// have to be added to media.json / published.json separately (see rockies-2018 in TEAM_HANDOFF.md).
//
// Usage: node scripts/fb-html-to-json.cjs <HTML export root> <out root> [extra-posts.json]
//   extra-posts.json: [{ timestamp, text }] — posts the export missed (optional)
const fs = require("fs");
const path = require("path");

const [src, out, extraFile] = process.argv.slice(2);
const postsDir = path.join(src, "your_facebook_activity", "posts");
// class and style attributes only get in the way of matching the structure
const load = f => fs.readFileSync(f, "utf8").replace(/ (?:class|style|id|aria-labelledby)="[^"]*"/g, "");
const html = load(path.join(postsDir, "your_posts__check_ins__photos_and_videos_1.html"));
const album = fs.readdirSync(path.join(postsDir, "album")).map(f => load(path.join(postsDir, "album", f))).join("");

const decode = s => s.replace(/<br \/>/g, "\n").replace(/<[^>]+>/g, "")
  .replace(/&quot;/g, '"').replace(/&#039;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
// Dates in the export are shown in the exporter's time zone (UTC-04:00, see "Generated by ...").
const MONTHS = { Jan: 0, Feb: 1, Mar: 2, Apr: 3, May: 4, Jun: 5, Jul: 6, Aug: 7, Sep: 8, Oct: 9, Nov: 10, Dec: 11 };
const ts = d => {
  const m = d.match(/(\w{3}) (\d{2}), (\d{4}) (\d{1,2}):(\d{2}):(\d{2}) (am|pm)/);
  let h = +m[4] % 12 + (m[7] === "pm" ? 12 : 0);
  return Date.UTC(+m[3], MONTHS[m[1]], +m[2], h + 4, +m[5], +m[6]) / 1000;
};
// FB's JSON stores UTF-8 text as Latin-1 characters; fb-archive-trip.cjs undoes that, so do it here.
const mojibake = s => Buffer.from(s, "utf8").toString("latin1");

// Time taken of each photo, from the album pages: <img src=".../<id>.jpg"> ... Taken ... <div>date</div>
const taken = {};
for (const m of album.matchAll(/media\/[\w]+\/(\d+)\.jpg" \/><\/a><table[^]*?<div>Taken<\/div><div><div>([^<]+)<\/div>/g))
  taken[m[1]] ??= ts(m[2]);

const posts = [];
for (const sec of html.split("<section").slice(1)) {
  const date = (sec.match(/<footer>.*?<div>([A-Z][a-z]{2} \d{2}, \d{4} [^<]+)<\/div>/) || [])[1];
  const imgs = [...sec.matchAll(/<img src="(your_facebook_activity\/posts\/media\/[^"]+)" \/><\/a><div>Photos<\/div>(?:<div>([^]*?)<\/div>)?<\/div>/g)];
  if (!date || !imgs.length) continue;  // birthday wishes on friends' walls etc.
  // the post text is the block right after the media grid
  const tail = sec.slice(sec.lastIndexOf("<div>Photos</div>"));
  const text = decode((tail.match(/<\/div><\/div><\/div><\/div><\/div><div><div>([^]*?)<\/div><div><\/div><\/div>/) || [])[1] || "");
  posts.push({
    timestamp: ts(date),
    data: [{ post: mojibake(text) }],
    attachments: [{ data: imgs.map(([, uri, cap]) => {
      const id = path.basename(uri, ".jpg");
      return { media: { uri, description: mojibake(cap ? decode(cap) : ""),
        media_metadata: { photo_metadata: { exif_data: [{ taken_timestamp: taken[id] || null }] } } } };
    }) }],
  });
}
for (const p of extraFile ? JSON.parse(fs.readFileSync(extraFile, "utf8")) : [])
  posts.push({ timestamp: p.timestamp, data: [{ post: mojibake(p.text) }], attachments: [] });

const outPosts = path.join(out, "your_facebook_activity", "posts");
fs.mkdirSync(outPosts, { recursive: true });
// fs.cpSync crashes Node on this machine with a Cyrillic source path, so copy file by file
const copyDir = (a, b) => {
  fs.mkdirSync(b, { recursive: true });
  for (const e of fs.readdirSync(a, { withFileTypes: true }))
    e.isDirectory() ? copyDir(path.join(a, e.name), path.join(b, e.name)) : fs.copyFileSync(path.join(a, e.name), path.join(b, e.name));
};
copyDir(path.join(postsDir, "media"), path.join(outPosts, "media"));
fs.writeFileSync(path.join(outPosts, "your_posts_1.json"), JSON.stringify(posts, null, 1));
for (const p of posts.sort((a, b) => a.timestamp - b.timestamp))
  console.log(new Date(p.timestamp * 1000).toISOString(), (p.attachments[0]?.data.length || 0) + " photos",
    Buffer.from(p.data[0].post, "latin1").toString("utf8").slice(0, 60).replace(/\n/g, " / "));
